import os
import subprocess
import sqlite3
import shutil
import ldap3
from ldap3.core.exceptions import LDAPException, LDAPEntryAlreadyExistsResult

class LdapManager:
    def __init__(self, db_path, conf_path="/etc/netlab/slapd.conf", db_dir="/var/lib/ldap"):
        self.db_path = db_path
        self.conf_path = conf_path
        self.db_dir = db_dir
        self.process = None

    def generate_config(self):
        os.makedirs(os.path.dirname(self.conf_path), exist_ok=True)
        os.makedirs(self.db_dir, exist_ok=True)
        
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        
        # Get settings
        cursor.execute("SELECT key, value FROM settings")
        settings = {row['key']: row['value'] for row in cursor.fetchall()}
        conn.close()
        
        enabled = settings.get("ldap_enabled") == "true"
        if not enabled:
            return False

        base_dn = settings.get("ldap_base_dn", "dc=netlab,dc=local")
        root_dn = settings.get("ldap_root_dn", "cn=admin,dc=netlab,dc=local")
        root_pw = settings.get("ldap_root_password", "adminpassword")
        
        # In a real environment, we'd hash the root password. For simplicity and standard lab use,
        # openldap supports cleartext passwords in slapd.conf if not hashed. Let's write it directly.
        # If we want a hashed password we could run `slappasswd -s <pw>`. Cleartext works perfectly for local labs.
        
        # Locate Debian/Ubuntu schema paths
        schema_dir = "/etc/ldap/schema"
        if not os.path.exists(schema_dir):
            schema_dir = "/etc/openldap/schema" # fallback
            
        config_lines = []
        config_lines.append("# Generated by NetLab Services Control Panel")
        
        # Include schemas
        schemas = ["core.schema", "cosine.schema", "inetorgperson.schema"]
        for schema in schemas:
            schema_path = os.path.join(schema_dir, schema)
            if os.path.exists(schema_path):
                config_lines.append(f"include {schema_path}")
                
        config_lines.append("")
        config_lines.append("pidfile /var/run/slapd.pid")
        config_lines.append("argsfile /var/run/slapd.args")
        config_lines.append("")
        
        # Module loading if needed (Debian loads them, Alpine has back-mdb built-in or in /usr/lib/openldap)
        module_paths = ["/usr/lib/ldap", "/usr/lib/openldap", "/usr/local/libexec/openldap"]
        module_path = None
        for path in module_paths:
            if os.path.exists(path):
                module_path = path
                break
                
        if module_path:
            # Only write modulepath and moduleload if we find the mdb shared library
            has_mdb = (
                os.path.exists(os.path.join(module_path, "back_mdb.la")) or 
                os.path.exists(os.path.join(module_path, "back_mdb.so"))
            )
            if has_mdb:
                config_lines.append(f"modulepath {module_path}")
                config_lines.append("moduleload back_mdb.la")
                config_lines.append("")
            
        config_lines.append("database mdb")
        config_lines.append(f"suffix \"{base_dn}\"")
        config_lines.append(f"rootdn \"{root_dn}\"")
        config_lines.append(f"rootpw \"{root_pw}\"")
        config_lines.append(f"directory {self.db_dir}")
        config_lines.append("maxsize 1073741824") # 1GB
        config_lines.append("")
        config_lines.append("index objectClass eq")
        config_lines.append("index cn,sn,mail pres,eq,sub")
        
        # Write config file
        with open(self.conf_path, "w") as f:
            f.write("\n".join(config_lines) + "\n")
            
        return True

    def start(self):
        self.stop()
        
        # Check if slapd binary is available
        if not shutil.which("slapd"):
            print("slapd binary not found. Cannot start LDAP.")
            return False
            
        enabled = self.generate_config()
        if not enabled:
            print("LDAP is disabled. slapd will not start.")
            return False
            
        try:
            # -h specify listener URI
            # -f specify slapd.conf
            # -d 0 runs it in foreground, outputs log to stdout.
            # We must run it as root or standard openldap user so it can write pid files.
            # Running as root is fine in GNS3 container.
            
            # Read LDAP port
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            cursor.execute("SELECT value FROM settings WHERE key='ldap_port'")
            row = cursor.fetchone()
            port = row[0] if row else "389"
            conn.close()
            
            cmd = ["slapd", "-h", f"ldap://0.0.0.0:{port}/", "-f", self.conf_path, "-d", "0"]
            self.process = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True
            )
            print("slapd started.")
            
            # Wait a moment for slapd to boot, then initialize directory
            import time
            time.sleep(1.0)
            self.initialize_directory()
            
            return True
        except Exception as e:
            print(f"Failed to start slapd: {e}")
            self.process = None
            return False

    def stop(self):
        if self.process:
            try:
                self.process.terminate()
                self.process.wait(timeout=2.0)
            except Exception:
                try:
                    self.process.kill()
                except Exception:
                    pass
            self.process = None
            print("slapd stopped.")

    def is_running(self):
        if self.process is None:
            return False
        return self.process.poll() is None

    def _get_ldap_connection(self):
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        cursor.execute("SELECT key, value FROM settings")
        settings = {row['key']: row['value'] for row in cursor.fetchall()}
        conn.close()
        
        port = settings.get("ldap_port", "389")
        root_dn = settings.get("ldap_root_dn", "cn=admin,dc=netlab,dc=local")
        root_pw = settings.get("ldap_root_password", "adminpassword")
        
        server = ldap3.Server(f"ldap://127.0.0.1:{port}", get_info=ldap3.ALL)
        # Bind using rootdn
        connection = ldap3.Connection(server, user=root_dn, password=root_pw, auto_bind=True)
        return connection, settings.get("ldap_base_dn", "dc=netlab,dc=local")

    def initialize_directory(self):
        if not self.is_running():
            return False
            
        try:
            conn, base_dn = self._get_ldap_connection()
            
            # Add top domain (e.g. dc=netlab,dc=local)
            # Find domain components (dc=netlab,dc=local -> netlab)
            # LDAP requires we create entries step by step if needed.
            # For simplicity, we write top-level domain entry
            try:
                # Add base DN
                # We split base DN to get the first domain component for dc attribute
                first_part = base_dn.split(',')[0]
                dc_val = first_part.split('=')[1]
                conn.add(base_dn, object_class=['top', 'domain'], attributes={'dc': dc_val})
                print(f"LDAP: Created base DN entry: {base_dn}")
            except LDAPEntryAlreadyExistsResult:
                pass
                
            # Add ou=users container
            try:
                conn.add(f"ou=users,{base_dn}", object_class=['top', 'organizationalUnit'], attributes={'ou': 'users'})
                print(f"LDAP: Created ou=users,{base_dn}")
            except LDAPEntryAlreadyExistsResult:
                pass
                
            # Add ou=groups container
            try:
                conn.add(f"ou=groups,{base_dn}", object_class=['top', 'organizationalUnit'], attributes={'ou': 'groups'})
                print(f"LDAP: Created ou=groups,{base_dn}")
            except LDAPEntryAlreadyExistsResult:
                pass
                
            # Re-sync existing SQLite LDAP users to slapd if they are missing
            self.sync_local_to_ldap(conn, base_dn)
            
            conn.unbind()
            return True
        except Exception as e:
            print(f"Failed to initialize LDAP directory tree: {e}")
            return False

    def sync_local_to_ldap(self, conn, base_dn):
        # Read local users and groups from SQLite and write them to OpenLDAP
        sqlite_conn = sqlite3.connect(self.db_path)
        sqlite_conn.row_factory = sqlite3.Row
        cursor = sqlite_conn.cursor()
        
        # Sync users
        cursor.execute("SELECT username, password, email, first_name, last_name FROM ldap_users")
        users = cursor.fetchall()
        for user in users:
            user_dn = f"cn={user['username']},ou=users,{base_dn}"
            try:
                attrs = {
                    'cn': user['username'],
                    'sn': user['last_name'] if user['last_name'] else user['username'],
                    'givenName': user['first_name'] if user['first_name'] else user['username'],
                    'mail': user['email'] if user['email'] else f"{user['username']}@netlab.local",
                    'userPassword': user['password']
                }
                conn.add(user_dn, object_class=['top', 'person', 'organizationalPerson', 'inetOrgPerson'], attributes=attrs)
                print(f"LDAP Sync: Added user {user['username']}")
            except LDAPEntryAlreadyExistsResult:
                pass
                
        # Sync groups
        cursor.execute("SELECT id, group_name FROM ldap_groups")
        groups = cursor.fetchall()
        for group in groups:
            group_dn = f"cn={group['group_name']},ou=groups,{base_dn}"
            
            # Fetch members for this group
            cursor.execute("""
                SELECT u.username FROM ldap_users u
                JOIN ldap_group_members m ON u.id = m.user_id
                WHERE m.group_id = ?
            """, (group['id'],))
            members = [f"cn={m['username']},ou=users,{base_dn}" for m in cursor.fetchall()]
            
            try:
                # groupOfNames require at least one member. If no members, we add rootDN as a member
                member_list = members if members else [conn.user]
                conn.add(group_dn, object_class=['top', 'groupOfNames'], attributes={
                    'cn': group['group_name'],
                    'member': member_list
                })
                print(f"LDAP Sync: Added group {group['group_name']}")
            except LDAPEntryAlreadyExistsResult:
                # If group exists, modify members list
                member_list = members if members else [conn.user]
                conn.modify(group_dn, {'member': [(ldap3.MODIFY_REPLACE, member_list)]})
                
        sqlite_conn.close()

    # --- Directory Modification APIs ---
    def add_user(self, username, password, email, first_name, last_name):
        # Insert to SQLite first
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        try:
            cursor.execute(
                "INSERT INTO ldap_users (username, password, email, first_name, last_name) VALUES (?, ?, ?, ?, ?)",
                (username, password, email, first_name, last_name)
            )
            conn.commit()
        except sqlite3.IntegrityError:
            conn.close()
            return False, "User already exists in database"
        conn.close()
        
        # Try writing to running OpenLDAP
        if self.is_running():
            try:
                ldap_conn, base_dn = self._get_ldap_connection()
                user_dn = f"cn={username},ou=users,{base_dn}"
                attrs = {
                    'cn': username,
                    'sn': last_name if last_name else username,
                    'givenName': first_name if first_name else username,
                    'mail': email if email else f"{username}@netlab.local",
                    'userPassword': password
                }
                ldap_conn.add(user_dn, object_class=['top', 'person', 'organizationalPerson', 'inetOrgPerson'], attributes=attrs)
                ldap_conn.unbind()
            except Exception as e:
                print(f"Warning: LDAP user created in DB but failed to push to OpenLDAP: {e}")
                
        return True, "User created successfully"

    def delete_user(self, username):
        # Fetch user ID
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        cursor.execute("SELECT id FROM ldap_users WHERE username=?", (username,))
        row = cursor.fetchone()
        if not row:
            conn.close()
            return False, "User not found"
            
        user_id = row[0]
        
        # Delete from SQLite (foreign keys handle members)
        cursor.execute("DELETE FROM ldap_users WHERE id=?", (user_id,))
        cursor.execute("DELETE FROM ldap_group_members WHERE user_id=?", (user_id,))
        conn.commit()
        conn.close()
        
        # Delete from running OpenLDAP
        if self.is_running():
            try:
                ldap_conn, base_dn = self._get_ldap_connection()
                user_dn = f"cn={username},ou=users,{base_dn}"
                ldap_conn.delete(user_dn)
                
                # Update all LDAP groups to remove this user from group membership list
                self.sync_groups_after_member_delete(ldap_conn, base_dn)
                
                ldap_conn.unbind()
            except Exception as e:
                print(f"Warning: LDAP user deleted from DB but failed to delete from OpenLDAP: {e}")
                
        return True, "User deleted successfully"

    def sync_groups_after_member_delete(self, ldap_conn, base_dn):
        sqlite_conn = sqlite3.connect(self.db_path)
        sqlite_conn.row_factory = sqlite3.Row
        cursor = sqlite_conn.cursor()
        
        cursor.execute("SELECT id, group_name FROM ldap_groups")
        groups = cursor.fetchall()
        for group in groups:
            group_dn = f"cn={group['group_name']},ou=groups,{base_dn}"
            cursor.execute("""
                SELECT u.username FROM ldap_users u
                JOIN ldap_group_members m ON u.id = m.user_id
                WHERE m.group_id = ?
            """, (group['id'],))
            members = [f"cn={m['username']},ou=users,{base_dn}" for m in cursor.fetchall()]
            
            member_list = members if members else [ldap_conn.user]
            try:
                ldap_conn.modify(group_dn, {'member': [(ldap3.MODIFY_REPLACE, member_list)]})
            except Exception:
                pass
        sqlite_conn.close()

    def add_group(self, group_name, description=""):
        # Insert to SQLite first
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        try:
            cursor.execute("INSERT INTO ldap_groups (group_name, description) VALUES (?, ?)", (group_name, description))
            conn.commit()
        except sqlite3.IntegrityError:
            conn.close()
            return False, "Group already exists"
        conn.close()
        
        # Create in running OpenLDAP
        if self.is_running():
            try:
                ldap_conn, base_dn = self._get_ldap_connection()
                group_dn = f"cn={group_name},ou=groups,{base_dn}"
                # A groupOfNames requires at least one member; we add rootDN as initial placeholder
                ldap_conn.add(group_dn, object_class=['top', 'groupOfNames'], attributes={
                    'cn': group_name,
                    'member': [ldap_conn.user]
                })
                ldap_conn.unbind()
            except Exception as e:
                print(f"Warning: LDAP group created in DB but failed to push to OpenLDAP: {e}")
                
        return True, "Group created successfully"

    def delete_group(self, group_name):
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        cursor.execute("SELECT id FROM ldap_groups WHERE group_name=?", (group_name,))
        row = cursor.fetchone()
        if not row:
            conn.close()
            return False, "Group not found"
            
        group_id = row[0]
        cursor.execute("DELETE FROM ldap_groups WHERE id=?", (group_id,))
        cursor.execute("DELETE FROM ldap_group_members WHERE group_id=?", (group_id,))
        conn.commit()
        conn.close()
        
        # Delete from running OpenLDAP
        if self.is_running():
            try:
                ldap_conn, base_dn = self._get_ldap_connection()
                group_dn = f"cn={group_name},ou=groups,{base_dn}"
                ldap_conn.delete(group_dn)
                ldap_conn.unbind()
            except Exception as e:
                print(f"Warning: LDAP group deleted from DB but failed to delete from OpenLDAP: {e}")
                
        return True, "Group deleted successfully"

    def update_group_members(self, group_name, usernames):
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        
        # Get group id
        cursor.execute("SELECT id FROM ldap_groups WHERE group_name=?", (group_name,))
        group_row = cursor.fetchone()
        if not group_row:
            conn.close()
            return False, "Group not found"
        group_id = group_row[0]
        
        # Clear members
        cursor.execute("DELETE FROM ldap_group_members WHERE group_id=?", (group_id,))
        
        # Add new members
        for uname in usernames:
            cursor.execute("SELECT id FROM ldap_users WHERE username=?", (uname,))
            u_row = cursor.fetchone()
            if u_row:
                cursor.execute("INSERT INTO ldap_group_members (group_id, user_id) VALUES (?, ?)", (group_id, u_row[0]))
                
        conn.commit()
        conn.close()
        
        # Sync to OpenLDAP
        if self.is_running():
            try:
                ldap_conn, base_dn = self._get_ldap_connection()
                group_dn = f"cn={group_name},ou=groups,{base_dn}"
                
                members_dn = [f"cn={uname},ou=users,{base_dn}" for uname in usernames]
                member_list = members_dn if members_dn else [ldap_conn.user]
                
                ldap_conn.modify(group_dn, {'member': [(ldap3.MODIFY_REPLACE, member_list)]})
                ldap_conn.unbind()
            except Exception as e:
                print(f"Warning: Group members updated in DB but failed to sync to OpenLDAP: {e}")
                
        return True, "Group membership updated"
