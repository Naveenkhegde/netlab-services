import os
import re
import subprocess
import sqlite3
import shutil

class TacacsManager:
    def __init__(self, db_path, conf_path="/etc/netlab/tac_plus.conf"):
        self.db_path = db_path
        self.conf_path = conf_path
        self.process = None

    def generate_config(self):
        os.makedirs(os.path.dirname(self.conf_path), exist_ok=True)
        
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        
        # Get settings
        cursor.execute("SELECT key, value FROM settings")
        settings = {row['key']: row['value'] for row in cursor.fetchall()}
        
        enabled = settings.get("tacacs_enabled") == "true"
        if not enabled:
            conn.close()
            return False

        default_secret = settings.get("tacacs_secret", "tacsecret")
        
        config_lines = []
        config_lines.append("# Generated by NetLab Services Control Panel")
        config_lines.append(f"key = \"{default_secret}\"")
        config_lines.append("")
        config_lines.append("# Global accounting logging")
        config_lines.append("accounting file = /var/log/tacacs_acct.log")
        config_lines.append("")

        # Clients (NAS)
        cursor.execute("SELECT ip_network, shared_secret FROM tacacs_clients")
        clients = cursor.fetchall()
        for client in clients:
            config_lines.append(f"client = {client['ip_network']} {{")
            config_lines.append(f"    key = \"{client['shared_secret']}\"")
            config_lines.append("}")
            config_lines.append("")

        # Users, privilege levels, and command authorization rules
        cursor.execute("SELECT * FROM tacacs_users")
        users = [dict(u) for u in cursor.fetchall()]

        for user in users:
            username = user["username"]
            default_act = user.get("default_action", "permit")
            config_lines.append(f"user = {username} {{")
            config_lines.append(f"    default service = {default_act}")
            config_lines.append(f"    password = clear \"{user['password']}\"")
            config_lines.append("    service = exec {")
            config_lines.append(f"        priv-lvl = {user['privilege']}")
            config_lines.append("    }")

            # Fetch user command authorization rules
            cursor.execute("SELECT * FROM tacacs_cmd_rules WHERE username = ? ORDER BY id ASC", (username,))
            rules = cursor.fetchall()
            for r in rules:
                cmd = r["command"].strip()
                regex = r["argument_regex"].strip() or ".*"
                act = r["action"]
                config_lines.append(f"    cmd = {cmd} {{")
                config_lines.append(f"        {act} \"{regex}\"")
                config_lines.append("    }")

            config_lines.append("}")
            config_lines.append("")

        conn.close()
        
        # Write config file
        with open(self.conf_path, "w") as f:
            f.write("\n".join(config_lines) + "\n")
            
        return True

    def test_authorization(self, username, full_command):
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()

        cursor.execute("SELECT * FROM tacacs_users WHERE username = ?", (username,))
        user = cursor.fetchone()
        if not user:
            conn.close()
            return {
                "status": "DENIED",
                "username": username,
                "command": full_command,
                "privilege": 0,
                "matched_rule": "User Not Found",
                "reason": f"TACACS+ User '{username}' does not exist."
            }

        user_dict = dict(user)
        default_action = user_dict.get("default_action", "permit").lower()

        # Parse command string
        parts = full_command.strip().split(maxsplit=1)
        base_cmd = parts[0] if parts else ""
        cmd_args = parts[1] if len(parts) > 1 else ""

        cursor.execute("SELECT * FROM tacacs_cmd_rules WHERE username = ? ORDER BY id ASC", (username,))
        rules = [dict(r) for r in cursor.fetchall()]
        conn.close()

        matched_rule = None
        final_action = default_action

        for r in rules:
            target_cmd = r["command"].strip()
            regex = r["argument_regex"].strip() or ".*"

            # Match command name or wildcard
            if target_cmd == "*" or target_cmd.lower() == base_cmd.lower():
                try:
                    if re.search(regex, cmd_args, re.IGNORECASE) or (not cmd_args and (regex == ".*" or regex == "")):
                        final_action = r["action"].lower()
                        matched_rule = f"cmd = {target_cmd} {{ {final_action} \"{regex}\" }}"
                        break
                except Exception as err:
                    print(f"Regex matching error in TACACS+ rule evaluation: {err}")

        is_permitted = final_action == "permit"
        status_text = "PERMITTED" if is_permitted else "DENIED"

        reason = f"Matched explicit rule: {matched_rule}" if matched_rule else f"No explicit rule matched. Applied user default service action: {default_action.upper()}"

        return {
            "status": status_text,
            "username": username,
            "command": full_command,
            "privilege": user_dict["privilege"],
            "default_action": default_action,
            "matched_rule": matched_rule or f"Default Service ({default_action})",
            "reason": reason
        }

    def start(self):
        self.stop()
        
        # Check if tac_plus binary is available
        if not shutil.which("tac_plus"):
            print("tac_plus binary not found. Cannot start TACACS+.")
            return False
            
        enabled = self.generate_config()
        if not enabled:
            print("TACACS+ is disabled. tac_plus will not start.")
            return False
            
        try:
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            cursor.execute("SELECT value FROM settings WHERE key='tacacs_port'")
            row = cursor.fetchone()
            port = row[0] if row else "49"
            conn.close()
            
            cmd = ["tac_plus", "-C", self.conf_path, "-G", "-p", port]
            self.process = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True
            )
            print("tac_plus started.")
            return True
        except Exception as e:
            print(f"Failed to start tac_plus: {e}")
            self.process = None
            return False

    def stop(self):
        if self.process:
            try:
                self.process.terminate()
                self.process.wait(timeout=2.0)
            except Exception:
                try:
                    self.process.kill()
                except Exception:
                    pass
            self.process = None
            print("tac_plus stopped.")

    def is_running(self):
        if self.process is not None and self.process.poll() is None:
            return True
        try:
            out = subprocess.check_output(["pgrep", "-f", "tac_plus"], text=True, stderr=subprocess.DEVNULL)
            return bool(out.strip())
        except Exception:
            return False
