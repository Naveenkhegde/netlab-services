import os
import subprocess
import sqlite3
import shutil

class DnsmasqManager:
    def __init__(self, db_path, conf_path="/etc/netlab/dnsmasq.conf", lease_path="/var/lib/misc/dnsmasq.leases"):
        self.db_path = db_path
        self.conf_path = conf_path
        self.lease_path = lease_path
        self.process = None

    def generate_config(self):
        os.makedirs(os.path.dirname(self.conf_path), exist_ok=True)
        os.makedirs(os.path.dirname(self.lease_path), exist_ok=True)
        
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        
        # Get settings
        cursor.execute("SELECT key, value FROM settings")
        settings = {row['key']: row['value'] for row in cursor.fetchall()}
        
        dns_enabled = settings.get("dns_enabled") == "true"
        dhcp_enabled = settings.get("dhcp_enabled") == "true"
        
        # If both are disabled, we don't need a config
        if not dns_enabled and not dhcp_enabled:
            conn.close()
            return False

        config_lines = []
        config_lines.append("# Generated by NetLab Services Control Panel")
        config_lines.append("keep-in-foreground")
        config_lines.append(f"dhcp-leasefile={self.lease_path}")
        
        # --- DNS Configuration ---
        if dns_enabled:
            config_lines.append("port=53")
            config_lines.append("domain-needed")
            config_lines.append("bogus-priv")
            config_lines.append("no-resolv")
            config_lines.append("no-poll")
            
            # Upstream servers
            upstream = settings.get("dns_upstream", "8.8.8.8")
            for server in upstream.split(","):
                server = server.strip()
                if server:
                    config_lines.append(f"server={server}")
                    
            # Custom DNS records from database
            cursor.execute("SELECT hostname, ip_address FROM dns_records")
            for record in cursor.fetchall():
                config_lines.append(f"address=/{record['hostname']}/{record['ip_address']}")
        else:
            # Disable DNS server port but allow DHCP to run
            config_lines.append("port=0")

        # --- DHCP Configuration ---
        if dhcp_enabled:
            interface = settings.get("dhcp_interface", "eth0")
            start = settings.get("dhcp_start", "192.168.1.100")
            end = settings.get("dhcp_end", "192.168.1.200")
            netmask = settings.get("dhcp_netmask", "255.255.255.0")
            lease_time = settings.get("dhcp_lease_time", "12h")
            gateway = settings.get("dhcp_gateway", "192.168.1.1")
            dns_servers = settings.get("dhcp_dns_servers", "")
            
            config_lines.append(f"interface={interface}")
            config_lines.append(f"dhcp-range={start},{end},{netmask},{lease_time}")
            
            if gateway:
                config_lines.append(f"dhcp-option=option:router,{gateway}")
                
            if dns_servers:
                config_lines.append(f"dhcp-option=option:dns-server,{dns_servers}")
                
            # Static DHCP leases
            cursor.execute("SELECT mac_address, ip_address, hostname FROM dhcp_static")
            for lease in cursor.fetchall():
                hostname_part = f",{lease['hostname']}" if lease['hostname'] else ""
                config_lines.append(f"dhcp-host={lease['mac_address']},{lease['ip_address']}{hostname_part}")

        conn.close()
        
        # Write config file
        with open(self.conf_path, "w") as f:
            f.write("\n".join(config_lines) + "\n")
            
        return True

    def start(self):
        self.stop()
        
        # Check if dnsmasq binary is available
        if not shutil.which("dnsmasq"):
            print("dnsmasq binary not found. Cannot start DNS/DHCP.")
            return False
            
        has_config = self.generate_config()
        if not has_config:
            print("Both DNS and DHCP are disabled. dnsmasq will not start.")
            return False
            
        try:
            # We run dnsmasq in the foreground (keep-in-foreground) inside a subprocess
            cmd = ["dnsmasq", "--conf-file=" + self.conf_path]
            self.process = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True
            )
            print("dnsmasq started.")
            return True
        except Exception as e:
            print(f"Failed to start dnsmasq: {e}")
            self.process = None
            return False

    def stop(self):
        if self.process:
            try:
                self.process.terminate()
                self.process.wait(timeout=2.0)
            except Exception:
                try:
                    self.process.kill()
                except Exception:
                    pass
            self.process = None
            print("dnsmasq stopped.")

    def is_running(self):
        if self.process is None:
            return False
        return self.process.poll() is None

    def get_active_leases(self):
        # Parses the dnsmasq lease file
        # Format: timestamp mac ip hostname client_id
        leases = []
        if not os.path.exists(self.lease_path):
            return leases
            
        try:
            with open(self.lease_path, "r") as f:
                for line in f:
                    parts = line.strip().split()
                    if len(parts) >= 3:
                        leases.append({
                            "mac": parts[1],
                            "ip": parts[2],
                            "hostname": parts[3] if parts[3] != "*" else "",
                        })
        except Exception as e:
            print(f"Error reading lease file: {e}")
        return leases
